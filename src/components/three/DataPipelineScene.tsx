interface DataPipelineSceneProps {
  selectedStageId: string;
  onSelectStage: (id: string) => void;
}

function FlowingParticles({ reducedMotion }: { reducedMotion: boolean }) {
  const count = 42;
  const pointsRef = useRef<THREE.Points>(null);

  const initialPositions = useMemo(() => {
    const arr = new Float32Array(count * 3);
    for (let i = 0; i < count; i++) {
      arr[i * 3] = -5 + (i / count) * 10;
      arr[i * 3 + 1] = 0.25 + (Math.random() - 0.5) * 0.25;
      arr[i * 3 + 2] = (Math.random() - 0.5) * 0.35;
    }
    return arr;
  }, []);

  useFrame((_, delta) => {
    if (reducedMotion || !pointsRef.current) return;
    const pos = pointsRef.current.geometry.attributes.position as THREE.BufferAttribute;
    for (let i = 0; i < count; i++) {
      let x = pos.getX(i) + delta * 1.6;
      if (x > 5) x = -5;
      pos.setX(i, x);
      pos.setY(i, 0.28 + Math.sin(x * 1.4 + i) * 0.12);
    }
    pos.needsUpdate = true;
  });

  return (
    <points ref={pointsRef}>
      <bufferGeometry>
        <bufferAttribute
          attach="attributes-position"
          count={count}
          array={initialPositions}
          itemSize={3}
        />
      </bufferGeometry>
      <pointsMaterial color="#00E5FF" size={0.09} transparent opacity={0.9} />
    </points>
  );
}

function PipelinePlatforms({
  selectedStageId,
  onSelectStage,
  reducedMotion,
}: DataPipelineSceneProps & { reducedMotion: boolean }) {
  const groupRef = useRef<THREE.Group>(null);

  useFrame((state) => {
    if (reducedMotion || !groupRef.current) return;
    groupRef.current.rotation.y = Math.sin(state.clock.elapsedTime * 0.25) * 0.06;
  });

  return (
    <group ref={groupRef}>
      {/* Connecting conduit beam */}
      <mesh position={[0, 0.05, 0]} rotation={[0, 0, Math.PI / 2]}>
        <cylinderGeometry args={[0.025, 0.025, 10, 12]} />
        <meshStandardMaterial color="#1E293B" emissive="#00E5FF" emissiveIntensity={0.35} />
      </mesh>

      <FlowingParticles reducedMotion={reducedMotion} />

      {PIPELINE_STAGES.map((stage, index) => {
        const x = -4.6 + index * 1.84;
        const isSelected = stage.id === selectedStageId;

        return (
          <group key={stage.id} position={[x, isSelected ? 0.18 : 0, 0]}>
            <mesh
              onClick={() => onSelectStage(stage.id)}
              onPointerOver={() => {
                document.body.style.cursor = 'pointer';
              }}
              onPointerOut={() => {
                document.body.style.cursor = 'default';
              }}
            >
              <boxGeometry args={[1.3, 0.22, 1.3]} />
              <meshStandardMaterial
                color={isSelected ? stage.color : '#111827'}
                emissive={stage.color}
                emissiveIntensity={isSelected ? 0.55 : 0.18}
                metalness={0.65}
                roughness={0.3}
              />
            </mesh>

            {/* Glowing data node on platform */}
            <mesh position={[0, 0.28, 0]}>
              <octahedronGeometry args={[0.18, 0]} />
              <meshStandardMaterial
                color={stage.color}
                emissive={stage.color}
                emissiveIntensity={isSelected ? 0.9 : 0.4}
              />
            </mesh>

            <Html position={[0, -0.45, 0]} center distanceFactor={9}>
              <button
                type="button"
                onClick={() => onSelectStage(stage.id)}
                className={`rounded-md px-2 py-1 font-mono text-[10px] whitespace-nowrap transition-all border ${
                  isSelected
                    ? 'border-[#00E5FF] bg-[#00E5FF]/20 text-[#F8FAFC]'
                    : 'border-white/15 bg-[#05070D]/85 text-[#94A3B8] hover:text-[#F8FAFC]'
                }`}
              >
                {stage.shortLabel}
              </button>
            </Html>
          </group>
        );
      })}
    </group>
  );
}

function PipelineFallback({ selectedStageId, onSelectStage }: DataPipelineSceneProps) {
  return (
    <div className="grid grid-cols-2 sm:grid-cols-3 lg:grid-cols-6 gap-3 p-4">
      {PIPELINE_STAGES.map((stage, i) => {
        const active = stage.id === selectedStageId;
        return (
          <button
            key={stage.id}
            type="button"
            onClick={() => onSelectStage(stage.id)}
            className={`rounded-2xl border p-4 text-left transition-all ${
              active
                ? 'border-[#00E5FF] bg-[#00E5FF]/10 shadow-cyanGlow'
                : 'border-white/10 bg-[#101827]/70 hover:border-white/25'
            }`}
          >
            <span className="font-mono text-[10px] text-[#94A3B8]">0{i + 1}</span>
            <p className="mt-1 font-display text-sm font-semibold text-[#F8FAFC]">
              {stage.title}
            </p>
          </button>
        );
      })}
    </div>
  );
}

export function DataPipelineScene({
  selectedStageId,
  onSelectStage,
}: DataPipelineSceneProps) {
  const prefersReducedMotion = usePrefersReducedMotion();
  const webgl = isWebGLAvailable();

  if (!webgl) {
    return (
      <PipelineFallback
        selectedStageId={selectedStageId}
        onSelectStage={onSelectStage}
      />
    );
  }

  return (
    <ErrorBoundary
      fallback={
        <PipelineFallback
          selectedStageId={selectedStageId}
          onSelectStage={onSelectStage}
        />
      }
    >
      <div className="h-[290px] sm:h-[340px] w-full rounded-3xl border border-white/10 bg-[#05070D]/75 overflow-hidden">
        <Canvas dpr={[1, 1.75]} camera={{ position: [0, 2.2, 7.6], fov: 42 }}>
          <ambientLight intensity={0.7} />
          <directionalLight position={[5, 8, 5]} intensity={1.2} />
          <pointLight position={[-4, 2, 3]} intensity={1.1} color="#00E5FF" />
          <pointLight position={[4, 2, -2]} intensity={1.1} color="#8B5CF6" />
          <Suspense fallback={null}>
            <PipelinePlatforms
              selectedStageId={selectedStageId}
              onSelectStage={onSelectStage}
              reducedMotion={prefersReducedMotion}
            />
          </Suspense>
        </Canvas>
      </div>
    </ErrorBoundary>
  );
}
